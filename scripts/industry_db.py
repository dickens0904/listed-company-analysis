# ── 通用分析框架 ──────────────────────────────────────────────────────────────

def get_industry_data(industry_name: str) -> dict:
    """
    获取行业数据，如果行业不存在则返回通用数据
    
    Args:
        industry_name: 行业名称
    
    Returns:
        dict: 行业数据
    """
    industry_lower = industry_name.lower() if industry_name else ""
    
    # 行业别名映射
    alias_map = {
        "光伏": "电力设备",
        "白酒": "食品饮料",
        "新能源汽车": "汽车",
        "人工智能": "计算机",
        "包装材料": "轻工制造",
        "化工": "基础化工",
        "医药": "医药生物",
        "电子": "电子",
        "机械": "机械设备",
        "建筑": "建筑装饰",
        "金融": "银行",
        "房地产": "房地产",
        "环保": "环保",
        "农业": "农林牧渔",
    }
    
    # 先尝试别名映射
    for alias, target in alias_map.items():
        if alias in industry_name:
            industry_name = target
            break
    
    # 查找匹配的行业
    for key in PRODUCT_MATRIX.keys():
        if key in industry_name:
            return {
                "industry": key,
                "product_matrix": PRODUCT_MATRIX.get(key, _default_product_matrix()),
                "technology_barriers": TECHNOLOGY_BARRIERS.get(key, _default_barriers()),
                "business_model": BUSINESS_MODELS.get(key, _default_business_model()),
                "customer_types": CUSTOMER_TYPES.get(key, _default_customer_types()),
                "geographic_dist": GEOGRAPHIC_DIST.get(key, _default_geographic_dist()),
                "pricing_strategy": PRICING_STRATEGIES.get(key, "市场定价"),
                "growth_strategies": GROWTH_STRATEGIES.get(key, _default_growth_strategies()),
            }
    
    # 未找到匹配行业，返回通用数据
    return {
        "industry": industry_name or "未知行业",
        "product_matrix": _default_product_matrix(),
        "technology_barriers": _default_barriers(),
        "business_model": _default_business_model(),
        "customer_types": _default_customer_types(),
        "geographic_dist": _default_geographic_dist(),
        "pricing_strategy": "市场定价",
        "growth_strategies": _default_growth_strategies(),
    }


def _default_product_matrix() -> dict:
    """默认产品矩阵"""
    return {
        "core": ["核心产品", "主营业务"],
        "growth": ["成长业务", "新市场"],
        "new": ["创新业务", "新方向"]
    }


